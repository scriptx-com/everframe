@implementation EverframeModule {
  // Strong ref to the bridge so we can look up RCTUIManager later.
  __weak RCTBridge *_bridge;
  // Session Vitals, owned PER MODULE INSTANCE (codex round-1, C4). It was a
  // process-wide `static` registry on the Swift `EverframeBridge`; React Native
  // does not guarantee one module instance, so that made two React instances
  // share one token space (the second instance's `rp1` was silently refused)
  // and let either one's `-invalidate` tear down the other's players. Android's
  // module has always held its registry as an instance field; this matches it.
  RemoteVitalsBridge *_vitals;
  // D1 fix (stale-teardown identity guard, spec 2026-09-17 setExtra-resolver).
  // Snapshot of `[EverframeBridge currentExtraResolveHookGeneration]` taken
  // right after THIS instance's most recent `-configure:` call — see
  // `EverframeBridge.resetExtraResolverForTeardown(_:)`'s doc comment for why
  // `-invalidate` must hand this back rather than tearing down unconditionally.
  // Zero-initialized by ObjC, matching `resetExtraResolverForTeardown(_:)`'s
  // "0 = never installed" no-op case for an instance whose `-configure:` was
  // never called (or never reached the install site) before `-invalidate`.
  NSInteger _extraResolveHookGeneration;
}

RCT_EXPORT_MODULE(Everframe)

- (instancetype)init {
  if (self = [super init]) {
    // Cheap: the registry allocates one lock and an empty map, nothing more —
    // which is also why `+requiresMainQueueSetup` can stay NO.
    _vitals = [RemoteVitalsBridge new];
  }
  return self;
}

+ (BOOL)requiresMainQueueSetup {
  // Module construction is cheap (Swift Bridge has no expensive init);
  // returning NO keeps RN's TurboModule cold-start fast. The methods that
  // need the main thread dispatch explicitly below.
  return NO;
}

- (void)setBridge:(RCTBridge *)bridge {
  _bridge = bridge;
}

// MARK: - configure(opts)

// Signature MUST match the codegen-emitted protocol in EverframeSpec.h:
//   - (void)configure:(JS::NativeEverframe::ConfigOpts &)opts;
// Field accessors (.apiKey(), .sdkVersion(), .captureScreenshot(),
// .networkBodiesDisabled()) are inline methods on the JS::NativeEverframe::
// ConfigOpts struct, generated from the TS spec in src/NativeEverframe.ts.
// The ingest URL is no longer JS-supplied — the native SDK bakes it at
// compile time via IngestEndpoint.url.
//
// NOTE (pre-existing, out of scope here): `captureScreenshot` is populated
// into ConfigOpts by extractBridgeConfig() but is never read below, so it is
// silently dropped on iOS today. Task 9 (spec 2026-08-12) only wires
// `networkBodiesDisabled` through; see task-9-report.md.
- (void)configure:(JS::NativeEverframe::ConfigOpts &)opts {
  NSString *appId = opts.apiKey() ?: @"";
  BOOL networkBodiesDisabled = opts.networkBodiesDisabled().value_or(false);
  // `installIdentifierDisabled` (MAI meter spec 2026-08-27) — `std::optional
  // <bool>`, same shape as `networkBodiesDisabled()` above. Absent means the
  // host said nothing, which is "send it": the SDK default is ON.
  BOOL installIdentifierDisabled = opts.installIdentifierDisabled().value_or(false);
  // `attachPinUi` (spec 2026-08-19) is a plain optional STRING field —
  // `opts.attachPinUi()` returns a nullable NSString*, same shape as
  // `opts.apiKey()` above, NOT the `std::optional<bool>` shape
  // `networkBodiesDisabled()` uses. `EverframeBridge.configure` coerces a
  // nil/unrecognised value to `.builtin`.
  NSString *attachPinUi = opts.attachPinUi();
  // `companionDeviceId` (naming spec 2026-08-24) is a plain optional STRING
  // field — same nullable-NSString* shape as `attachPinUi` above, not the
  // `std::optional<bool>` shape `networkBodiesDisabled()` uses.
  NSString *companionDeviceId = opts.companionDeviceId();
  // `companionBadgeEnabled`/`companionBadgePosition` (naming spec
  // 2026-08-24, controller ruling / Task 6b) — flat fields on ConfigOpts;
  // RN codegen cannot express the nested `{enabled, position}` shape the JS
  // facade's `RuntimeConfig.companionBadge` uses, so `extractBridgeConfig`
  // flattens it before it crosses. `companionBadgeEnabled()` is
  // `std::optional<bool>`, same shape as `networkBodiesDisabled()` above;
  // absent defaults to `true` (badge shown), matching
  // `CompanionBadgeOptions.enabled`'s own default. `companionBadgePosition()`
  // is a nullable NSString*, same shape as `attachPinUi`/`companionDeviceId`
  // above; `EverframeBridge` coerces nil/unrecognised to `.bottomRight`.
  BOOL companionBadgeEnabled = opts.companionBadgeEnabled().value_or(true);
  BOOL shakeToReportEnabled = opts.shakeToReportEnabled().value_or(true);
  NSString *companionBadgePosition = opts.companionBadgePosition();
  // Inline reporter theme (reporter branding spec 2026-08-25, RN slice) —
  // 8 flat optional STRING fields on ConfigOpts (RN codegen cannot express
  // the nested `theme: { … }` shape the JS facade's `RuntimeConfig.theme`
  // uses; `extractBridgeConfig` flattens it before it crosses). Collapsed
  // here into ONE role-keyed dictionary so the Swift seam gains a single
  // `theme:` parameter instead of eight — nil when the host set no theme,
  // preserving "host did nothing" through to `EverframeConfig.theme`.
  // Values cross unvalidated; the sdk-ios ThemeResolver revalidates hex
  // per-field at presentation time.
  NSMutableDictionary<NSString *, NSString *> *theme = [NSMutableDictionary new];
  if (opts.themeBackground()) theme[@"background"] = opts.themeBackground();
  if (opts.themeSurface()) theme[@"surface"] = opts.themeSurface();
  if (opts.themeBorder()) theme[@"border"] = opts.themeBorder();
  if (opts.themeText()) theme[@"text"] = opts.themeText();
  if (opts.themeTextMuted()) theme[@"textMuted"] = opts.themeTextMuted();
  if (opts.themeAccent()) theme[@"accent"] = opts.themeAccent();
  if (opts.themeAccentForeground()) theme[@"accentForeground"] = opts.themeAccentForeground();
  if (opts.themeDestructive()) theme[@"destructive"] = opts.themeDestructive();
  // Session Vitals (spec 2026-09-06) — three flat optional fields on
  // ConfigOpts (RN codegen cannot express the nested `vitals` object the JS
  // facade uses; `extractBridgeConfig` flattens it before it crosses).
  // `std::optional<bool>` / `std::optional<double>` shapes, same as
  // `networkBodiesDisabled()` above — but forwarded as NSNumber* (nil =
  // absent) rather than collapsed with `.value_or(...)`, because the Swift
  // seam MUST be able to tell "absent" from "false": absent `vitalsEnabled`
  // means "follow the dashboard toggle", while `false` is a local opt-out.
  NSNumber *vitalsEnabled = opts.vitalsEnabled().has_value() ? @(opts.vitalsEnabled().value()) : nil;
  NSNumber *vitalsSampleRate = opts.vitalsSampleRate().has_value() ? @(opts.vitalsSampleRate().value()) : nil;
  NSNumber *vitalsCaptureSourceQuery = opts.vitalsCaptureSourceQuery().has_value() ? @(opts.vitalsCaptureSourceQuery().value()) : nil;
  NSError *err = nil;
  [EverframeBridge configureWithAppId:appId
                            endpoint:@""
               networkBodiesDisabled:networkBodiesDisabled
           installIdentifierDisabled:installIdentifierDisabled
                         attachPinUi:attachPinUi
                   companionDeviceId:companionDeviceId
               companionBadgeEnabled:companionBadgeEnabled
                  shakeToReportEnabled:shakeToReportEnabled
              companionBadgePosition:companionBadgePosition
                               theme:(theme.count > 0 ? theme : nil)
                       vitalsEnabled:vitalsEnabled
                    vitalsSampleRate:vitalsSampleRate
            vitalsCaptureSourceQuery:vitalsCaptureSourceQuery
                               error:&err];
  if (err != nil) {
    // Configure is void-typed at the spec; we can't reject a promise here.
    RCTLogWarn(@"[everframe] configure failed: %@", err.localizedDescription);
  }
  // D1 fix (stale-teardown identity guard, spec 2026-09-17 setExtra-resolver).
  // Capture whichever installation is live right now — regardless of whether
  // `err` fired above — and stash it on this instance for `-invalidate` to
  // hand back to `resetExtraResolverForTeardown:`. See that method's doc
  // comment on EverframeBridge.swift for the race this closes.
  _extraResolveHookGeneration = [EverframeBridge currentExtraResolveHookGeneration];
  // Codex round-5 — nothing re-registers the live players here any more. `renewAll()` raced
  // the runtime's deferred-registration drain (it could detach the replacement it had just
  // installed) and only ever reached THIS module instance's registry. The replacement is two
  // parts, neither of them native: `EverframeBridge.configure` SKIPS the restart entirely when
  // the effective options are unchanged and the SDK is already started, and when it does
  // restart, the JS `configureEpoch` bump re-runs every vitals hook effect — each one
  // detaching its old token and tracking a fresh one against the SDK that is now current.
}

// Additive synchronous startup entry. The legacy void selector above stays
// ABI-compatible for already-compiled callers; current JS uses this boolean
// method so its first synchronous capture cannot overtake configure dispatch.
- (NSNumber *)configureSync:(JS::NativeEverframe::ConfigOpts &)opts {
  [self configure:opts];
  return @YES;
}

// MARK: - openReporter() -> Promise<object>

// Opens the native TXReporterPresenter modal. Resolves with
//   { status: "submitted" | "queued" | "cancelled", reportId?: <uuid> }
- (void)openReporter:(RCTPromiseResolveBlock)resolve
              reject:(RCTPromiseRejectBlock)reject {
  [EverframeBridge openReporterWithCompletion:^(NSDictionary *result, NSError *err) {
    if (err) {
      reject(@"open_reporter_failed", err.localizedDescription, err);
    } else {
      resolve(result ?: @{});
    }
  }];
}

// MARK: - registerSensitiveRect(viewTag, rect)

// `viewTag` is `double` per RN codegen rules (numbers cross as double).
// `rect` is the codegen-typed JS::NativeEverframe::Rect — informational only;
// the native registry resolves the view's actual frame at capture time.
// We intentionally don't read .x()/.y()/.width()/.height() here — they're
// available if a future iteration needs hint-based registration.
- (void)registerSensitiveRect:(double)viewTag
                         rect:(JS::NativeEverframe::Rect &)rect {
  __weak RCTBridge *weakBridge = _bridge;
  NSNumber *tag = @((NSInteger)viewTag);
  dispatch_async(dispatch_get_main_queue(), ^{
    RCTBridge *strongBridge = weakBridge;
    UIView *view = nil;
    if (strongBridge != nil) {
      view = [strongBridge.uiManager viewForReactTag:tag];
    }
    // Bridge does a nil-check + warn-once (Pitfall P5 / T-06-02-03).
    [EverframeBridge markSensitiveViewOrWarn:view];
  });
}

