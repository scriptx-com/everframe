// MARK: - Session Vitals (spec 2026-09-06) — five void, fire-and-forget methods

// Pure forwarding, no validation: `_vitals`'s `RemotePlayerRegistry` (one per
// module instance since codex round-1 C4) owns the token map, the 32-token cap and the epoch-ms sanity check, and
// every one of its methods is a silent no-op for an unknown token — a bridge
// must never throw into a host. `data`/`stats` are the spec's `UnsafeObject`
// escape hatch; codegen declares them `NSDictionary *`, but we take `id` and
// class-check — exactly what `addBreadcrumb`/`recordScreen` above do, since
// nothing enforces the declared type at the JSI boundary and a non-dictionary
// payload must be treated as absent rather than crash on a bad selector. `t`
// is a REQUIRED double (the spec types it `t: number`, not `t?: number` — an
// event with no timestamp is unorderable, so JS always supplies one).

- (void)trackPlayer:(NSString *)token
            library:(NSString *)library
               name:(NSString *)name
     libraryVersion:(NSString *)libraryVersion {
  [_vitals trackPlayer:(token ?: @"")
               library:(library ?: @"")
                  name:name
        libraryVersion:libraryVersion];
}

- (void)detachPlayer:(NSString *)token {
  [_vitals detachPlayer:(token ?: @"")];
}

- (void)recordPlayerEvent:(NSString *)token
                     type:(NSString *)type
                        t:(double)t
                     data:(id)data {
  NSDictionary *dataDict = [data isKindOfClass:[NSDictionary class]] ? (NSDictionary *)data : nil;
  [_vitals recordPlayerEvent:(token ?: @"") type:(type ?: @"") t:t data:dataDict];
}

// `stats` is REQUIRED at the spec (`stats: UnsafeObject`, no `?`), but the
// class-check still matters: a non-dictionary value is DROPPED here rather
// than passed on as an empty snapshot, which would clobber the player's live
// stats with zeros.
- (void)updatePlayerStats:(NSString *)token stats:(id)stats {
  NSDictionary *statsDict = [stats isKindOfClass:[NSDictionary class]] ? (NSDictionary *)stats : nil;
  if (statsDict == nil) return;
  [_vitals updatePlayerStats:(token ?: @"") stats:statsDict];
}

// `dataJson` is a pre-serialised JSON STRING, not UnsafeObject — custom vitals
