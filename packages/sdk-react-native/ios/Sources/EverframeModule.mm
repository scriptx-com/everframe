// Unparseable JSON is recorded WITHOUT data by the registry, never dropped.
- (void)trackVitals:(NSString *)name dataJson:(NSString *)dataJson token:(NSString *)token {
  [_vitals trackVitals:(name ?: @"") dataJson:dataJson token:token];
}

// Module-instance teardown (RN tears the instance down on a Metro/OTA reload,
// and on host shutdown). Detach every player registered through THIS INSTANCE
// so their play/buffer spans close natively — since codex round-1 C1 the
// integration's own `detach()` emits the closing `buffer_end`/`pause`, so the
// spans really close instead of accruing to the end of the session — and so
// the reloaded bundle's re-minted `rp1` is not shadowed by the dead one.
//
// LIFETIME (rewritten for C4): the registry is now PER MODULE INSTANCE, exactly
// like Android's, so this teardown touches only the players this instance
// registered. It no longer reaches a process-wide map, which is what let one
// React instance detach another's players. The teardown is terminal — the
// reload builds a NEW module instance with a NEW registry for the new bundle,
// so nothing legitimate can still be calling the closed one.
//
// NOT done in `configure:`: a screen's `useTrackPlayer` effect runs BEFORE the
// Provider's configure-on-mount, so clearing there would drop legitimate
// registrations that had already landed.
- (void)invalidate {
  [_vitals reset];
  // Review finding F4 (spec 2026-09-17 setExtra-resolver) — see
  // `EverframeBridge.resetExtraResolverForTeardown`'s doc comment for why
  // this must run here: without it, a JS-context teardown that skips
  // `runtime.unmount()` leaves the extra-resolver presence flag stuck
  // true, so every later report (including pure-native ones) pays the
  // full 250ms ask-and-wait for an ack nobody will ever send.
  //
  // D1 fix: `_extraResolveHookGeneration` (captured at the end of
  // `-configure:`) travels with this instance so the Swift side can tell a
  // STALE instance's `-invalidate` — delivered late, on this module's
  // method queue, after a reloaded bundle's fresh instance already
  // reconfigured — from the CURRENT one, and no-op the former. See
  // `EverframeBridge.resetExtraResolverForTeardown(_:)`'s doc comment for
  // the full race this closes.
  [EverframeBridge resetExtraResolverForTeardown:_extraResolveHookGeneration];
}

// MARK: - setUser(user?) — self-declared identity (spec 2026-08-12)

// The spec types this bridge parameter `UnsafeObject`, NOT the named
// `EverframeUserSpec` alias — codegen's ObjC generator ignores `?` optionality on a
// named struct-alias param (TypeAliasTypeAnnotation) and always emits a
// REQUIRED `JS::NativeEverframe::EverframeUserSpec &` reference, which would make
// "no argument = clear" unrepresentable. `UnsafeObject` resolves to
// GenericObjectTypeAnnotation, which DOES honour `?` and generates the
// nullable `(NSDictionary *)user` protocol signature — verified against
// this repo's installed `@react-native/codegen` (see NativeEverframe.ts's
// file header for the full writeup). `(id)` here matches `addBreadcrumb`'s
// `data` param below, which crosses the same GenericObjectTypeAnnotation
// shape; `id` is compatible with the generated `NSDictionary *` protocol
// type. `EverframeBridge` re-validates and pulls out id/email/displayName
// defensively.
- (void)setUser:(id)user {
  NSDictionary *dict = [user isKindOfClass:[NSDictionary class]] ? (NSDictionary *)user : nil;
  [EverframeBridge setUser:dict];
}

