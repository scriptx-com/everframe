    private fun captureCrashJson(crashJson: String, handled: Boolean): Boolean {
        return try {
            val obj = org.json.JSONObject(crashJson)
            val frames = obj.optJSONArray("framesRaw")?.let { arr ->
                List(minOf(arr.length(), 256)) { i ->
                    val raw = arr.get(i)
                    require(raw is String) { "framesRaw entries must be strings" }
                    raw.take(1024)
                }
            } ?: emptyList()
            val exceptionType = obj.optString("exceptionType", "Error").take(256)
            val message = obj.optString("message", "").take(4096)
            val occurredAt = obj.optString("occurredAt", java.time.Instant.now().toString())
            // Optional enrichment must never prevent capture of the raw facts.
            val jsBundle = runCatching {
                obj.optJSONObject("jsBundle")?.let { metadata ->
                    kotlinx.serialization.json.Json { ignoreUnknownKeys = true }
                        .decodeFromString<dev.everframe.protocol.generated.JSBundle>(metadata.toString())
                }
            }.getOrNull()
            val details = if (obj.has("details")) obj.get("details") else null
            val causeChain = if (obj.has("causeChain")) obj.get("causeChain") else null
            val fatal = !handled && obj.optBoolean("fatal", false)
            // Only errors the app survives ask for a replay. Eligibility and export remain in the core;
            // fatal errors keep the entry point that never carries a replay.
            val accepted = when {
                handled -> dev.everframe.crash.CrashReporter.captureHandledFactsWithReplay(
                    exceptionType, message, frames, occurredAt, jsBundle, details, causeChain, "everframe-android",
                )
                fatal -> dev.everframe.crash.CrashReporter.captureFactsAcceptedWithCauses(
                    exceptionType, message, frames, obj.optString("mechanism", "errorutils"),
                    fatal, occurredAt, jsBundle, details, causeChain,
                )
                else -> dev.everframe.crash.CrashReporter.captureFactsAcceptedWithReplay(
                    exceptionType, message, frames, obj.optString("mechanism", "errorutils"),
                    fatal, occurredAt, jsBundle, details, causeChain,
                )
            }
            // Scheduling is best-effort after acceptance; a scheduler failure
            // cannot undo completed storage or make JS account it as refused.
            if (accepted && !fatal) runCatching { __drainRequester() }
            accepted
        } catch (_: Throwable) {
            false
        }
    }

