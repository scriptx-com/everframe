    /** A bridge bug must never crash the host. Mirrors txGuardVoid from Everframe.kt. */
    private inline fun txGuardVoid(api: String, body: () -> Unit) {
        try {
            body()
        } catch (t: Throwable) {
            android.util.Log.w("Everframe.rn", "guarded exception in $api: ${t.message}")
        }
    }

    private inline fun txGuardSurface(api: String, body: () -> Unit) {
        try {
            body()
        } catch (t: JSApplicationIllegalArgumentException) {
            throw t
        } catch (t: Throwable) {
            android.util.Log.w("Everframe.rn", "guarded exception in $api: ${t.message}")
        }
    }

