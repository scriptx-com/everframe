    /**
     * Forward a host-declared user from JS into `Everframe.setUser`. The
     * singleton owns storage AND gating (no-op pre-start / while killed via its
     * own `txGuardVoid` + `captureGate` check), exactly like
     * `setExtra`/`addBreadcrumb` above never re-check `captureGate` themselves.
     * A missing key becomes `null`, never an empty string — that's what keeps
     * the Task 9 email-only `TXUser` shape (nullable `id`) usable.
     *
     * External review, finding 2 (Serious) — reads are TYPE-checked
     * ([stringOrNull]), not merely key-presence-checked. `getString(key)` THROWS
     * on a non-string value, and `txGuardVoid` swallows that exception BEFORE
     * `Everframe.setUser()` is reached: `setUser({ id: 12345 })` was therefore a
     * silent no-op that left the PREVIOUS account installed, so every subsequent
     * report — crashes included — stayed attributed to someone the host had
     * explicitly replaced. That is the one outcome worse than losing the user
     * entirely.
     *
     * The primary fix is the JS projection in `src/user-projection.ts`, applied
     * before the value ever crosses the bridge. This is the second layer, for a
     * hand-wired native caller (or a host on an older JS bundle) that reaches
     * this method directly: bad fields degrade to `null` — a partial user, or
     * anonymous — and `Everframe.setUser` is ALWAYS reached, so the call always
     * replaces what was installed before.
     */
    @ReactMethod
    override fun setUser(user: ReadableMap?) {
        txGuardVoid("setUser") {
            if (user == null) {
                Everframe.setUser(null)
                return@txGuardVoid
            }
            Everframe.setUser(
                TXUser(
                    id = user.stringOrNull("id"),
                    email = user.stringOrNull("email"),
                    displayName = user.stringOrNull("displayName"),
                )
            )
        }
    }

    /**
     * `getString(key)` only when the value really IS a string; `null` for a
     * missing key, an explicit JS `null`, or any other type (number, boolean,
     * object, array). See [setUser] — `ReadableMap.getString` throws on a type
     * mismatch, and a throw here costs the whole call, not just the field.
     *
     * [hasKey] is still checked FIRST and is not redundant:
     * `ReadableNativeMap.getType` throws `NoSuchKeyException` for a key that
     * isn't present, so type-checking alone would turn the ordinary partial
     * user (`{ email }` with no `id` — the Task 9 shape this API exists to
     * support) into the very swallowed-throw this fix removes.
     *
     * Wrapped in `runCatching` because the contract this helper exists to
     * enforce is "never throws": these are the two throwing cases known today,
     * and a third one from a future RN `ReadableMap` implementation must cost
     * its own field, not the whole `setUser` call.
     */
    private fun ReadableMap.stringOrNull(key: String): String? =
        runCatching {
            if (hasKey(key) && getType(key) == ReadableType.String) getString(key) else null
        }.getOrNull()

