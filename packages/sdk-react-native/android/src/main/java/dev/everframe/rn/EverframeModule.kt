    // ---------------- Session Vitals (spec 2026-09-06) ----------------

    /**
     * Token → registration map. Lives in everframe-core (tested there); this
     * module is glue — NO validation here (unknown tokens, out-of-range
     * timestamps and the 32-token cap are all the registry's business, and
     * every one of its methods is a silent no-op rather than a throw).
     *
     * `captureSourceQuery` is a PROVIDER lambda resolved at attach time
     * (I13), never a value read once at configure() — a host that reconfigures
     * mid-session must get the new answer for players attached afterwards.
     *
     * LIFETIME: cleared in `invalidate()`, i.e. when this module instance is
     * torn down — which is exactly what a Metro/OTA reload does. That matters
     * because JS mints tokens from a per-bundle counter that restarts at
     * `rp1`: without the reset, the previous bundle's registrations would keep
     * accumulating play/buffer time natively AND shadow the re-minted tokens
     * (`track` refuses a token that is still live). A bare `Everframe.kill()`
     * does NOT clear it — the module instance survives that, and the JS hooks
     * still own detach for every player they registered.
     */
    private val remotePlayers = dev.everframe.vitals.RemotePlayerRegistry(
        register = { integration, name -> Everframe.trackPlayer(integration, name) },
        sessionTrack = { name, data -> Everframe.trackVitals(name, data, null) },
        captureSourceQuery = { Everframe.currentConfig?.vitals?.captureSourceQuery ?: false },
    )

    @ReactMethod
    override fun trackPlayer(token: String, library: String, name: String?, libraryVersion: String?) {
        txGuardVoid("trackPlayer") { remotePlayers.track(token, library, name, libraryVersion) }
    }

    @ReactMethod
    override fun detachPlayer(token: String) {
        txGuardVoid("detachPlayer") { remotePlayers.detach(token) }
    }

    @ReactMethod
    override fun recordPlayerEvent(token: String, type: String, t: Double, data: ReadableMap?) {
        txGuardVoid("recordPlayerEvent") { remotePlayers.record(token, type, t, data?.toHashMap()) }
    }

    @ReactMethod
    override fun updatePlayerStats(token: String, stats: ReadableMap) {
        txGuardVoid("updatePlayerStats") { remotePlayers.updateStats(token, stats.toHashMap()) }
    }

    @ReactMethod
    override fun trackVitals(name: String, dataJson: String?, token: String?) {
        txGuardVoid("trackVitals") { remotePlayers.trackVitals(name, dataJson, token) }
    }

    /**
     * Module-instance teardown (RN tears the instance down on a Metro/OTA
     * reload, and on host shutdown). Detach every player this instance
     * registered so their play/buffer spans close natively instead of being
     * accumulated forever against a bundle that no longer exists — and so the
     * reloaded bundle's re-minted `rp1` is not shadowed by the dead one.
     *
     * NOT done in `configure()`: a screen's `useTrackPlayer` effect runs
     * BEFORE the Provider's configure-on-mount, so clearing there would drop
     * legitimate registrations that had already landed.
     */
    override fun invalidate() {
        sensitiveRegistration.close()
        videoPrivacyAdapter.close()
        super.invalidate()
        txGuardVoid("invalidate") { remotePlayers.detachAll() }
        // Review finding F4 (spec 2026-09-17 setExtra-resolver). Unlike
        // iOS's process-static flag, `extraResolverActive` here is already
        // per-instance and dies with this module — but the HOOK it backs is
        // stored on the `Everframe` singleton, so without this it would go on
        // referencing an invalidated module instance forever after a
        // JS-context teardown that skips `runtime.ts`'s `unmount()` (a hard
        // reload, or a native host tearing the `ReactInstanceManager` down
        // directly). The identity check (`extraResolveHook` field doc
        // comment above) guards against clobbering a NEWER instance's hook
        // if this invalidate() races behind its constructor.
        if (Everframe.__pendingExtraResolveHook === extraResolveHook) {
            Everframe.__pendingExtraResolveHook = null
        }
        extraResolverActive = false
    }

