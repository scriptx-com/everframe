// `packages/sdk-react-native/src/NativeEverframe.ts`):
//
//   configure(opts)                       → void
//   configureSync(opts)                   → boolean (SYNC — startup boundary)
//   openReporter()                        → Promise<{status, reportId?}>
//   registerSensitiveRect(viewTag, rect)  → void
//   setExtra(value)                       → void
//   setExtraResolverActive(active)        → void           (spec 2026-09-17)
//   signalExtraResolverReady(id)          → void           (spec 2026-09-17)
//   addBreadcrumb(message, kind?, level?, data?) → void   (Plan 4 / Task 14)
//   recordScreen(name, data?)             → void           (spec 2026-07-14)
//   reportCrash(crashJson)                → boolean (SYNC — spec 2026-07-18)
//   setUser(user?)                        → void           (spec 2026-08-12)
//   trackPlayer/detachPlayer/recordPlayerEvent/updatePlayerStats/
//   trackVitals                           → void           (spec 2026-09-06)
//   configureSync(opts.vitals*)           → boolean        (spec 2026-09-06)
//   addListener(name)/removeListeners(n)  → void (RN event-emitter no-ops)
//
// The native TXReporterPresenter owns the entire report UX (capture, annotate,
// redact, submit). JS provides the host React context, host-owned triggers,
// and the sensitive-rect bridge. Native mobile shake stays below this bridge.
//
// THREADING:
//   • configureSync runs on the JS thread (blocking synchronous).
//   • openReporter dispatches presenter.openReporter onto the activity from
//     MainScope (presenter manages its own UI thread hops internally).
//   • registerSensitiveRect runs on the UI thread (UIManager view resolution).
//
// CODEGEN:
//   `dev.everframe.rn.NativeEverframeSpec` is generated by the
//   `com.facebook.react` Gradle plugin from `packages/sdk-react-native/src/
//   NativeEverframe.ts`. The bridge build.gradle.kts now applies that plugin
//   directly (see 33734a8), so the abstract spec class is on this library's
//   compile classpath. We extend it so the module is recognised as a
//   TurboModule at runtime (the spec implements
//   `com.facebook.react.turbomodule.core.interfaces.TurboModule`). Without
//   that interface, `TurboModuleRegistry.getEnforcing('Everframe')` rejects
