    @ReactMethod(isBlockingSynchronousMethod = true)
    override fun configureSync(opts: ReadableMap): Boolean = configureInternal(opts)

    private fun configureInternal(opts: ReadableMap): Boolean {
        var completed = false
        txGuardSurface("configure") {
            val sdkKey = opts.takeIfHasString("apiKey")
                ?: throw JSApplicationIllegalArgumentException(
                    "configure: required field 'apiKey' missing",
                )
            val sdkVersion = opts.takeIfHasString("sdkVersion") ?: Everframe.SDK_VERSION

            // Ingest URL is baked into the AAR at build time per Gradle
            // variant (release = prod, debug = EVERFRAME_DEV_INGEST_URL).
            // The JS-side `apiBase` field is no longer plumbed through.
            // Polarity flips exactly once, here: JS sends the veto
            // (`networkBodiesDisabled`), native stores the permission.
            val networkBodiesDisabled = opts.takeIfHasBoolean("networkBodiesDisabled") ?: false
            // Polarity flips exactly once, here: JS sends the veto
            // (`installIdentifierDisabled`), native stores the permission.
            val installIdentifierDisabled = opts.takeIfHasBoolean("installIdentifierDisabled") ?: false
            // Attach-PIN UI mode (spec 2026-08-19) — a flat optional STRING
            // field (codegen cannot express a string-literal union), parsed
            // here and stashed for `startCompanion()` to read (the flag is a
            // startup-time preference riding `configure()`, not a per-call
            // argument; see NativeEverframe.ts's D-decision header note).
            // Absent/unrecognised both coerce to BUILTIN, the safe default
            // matching "host did nothing special". Parsed into a LOCAL: the
            // idempotence gate below compares it against the stashed value
            // before deciding, and only the start path adopts it.
            val attachPinUi = parseAttachPinUi(opts.takeIfHasString("attachPinUi"))

            val config = EverframeConfig(
                appId = sdkKey,
                sdkKey = sdkKey,
                environment = Environment.production,
                release = sdkVersion,
                capture = CaptureConfig(networkBodies = !networkBodiesDisabled),
                installIdentifierEnabled = !installIdentifierDisabled,
                // Explicit companion device-identity override (naming spec
                // 2026-08-24) — read straight off the flat ConfigOpts field,
                // same shape as attachPinUi above. Absent/blank falls
                // through to the SSAID-then-stored-UUID chain inside
                // CompanionDeviceId.resolve.
                companionDeviceId = opts.takeIfHasString("companionDeviceId"),
                // Companion on-screen name badge (naming spec 2026-08-24,
                // controller ruling / Task 6b) — flat fields on ConfigOpts
                // (RN codegen cannot express the nested `{enabled,
                // position}` shape the JS facade's
                // `RuntimeConfig.companionBadge` uses; `extractBridgeConfig`
                // flattens it before it crosses). Absent `enabled` defaults
                // to `true` (badge shown); `position` is stashed raw here
                // and parsed into `CompanionBadgePosition` only at
                // `startCompanion()` time, mirroring `attachPinUi`.
                companionBadgeEnabled = opts.takeIfHasBoolean("companionBadgeEnabled") ?: true,
                shakeToReportEnabled = opts.takeIfHasBoolean("shakeToReportEnabled") ?: true,
                companionBadgePosition = opts.takeIfHasString("companionBadgePosition"),
                // Inline reporter theme (reporter branding spec 2026-08-25,
                // RN slice) — 8 flat optional STRING fields on ConfigOpts
                // (RN codegen cannot express the nested `theme: { … }` shape
                // the JS facade's `RuntimeConfig.theme` uses;
                // `extractBridgeConfig` flattens it before it crosses).
                // Collapses to null when the host set no theme, preserving
                // "host did nothing". Values cross unvalidated; the core
                // ThemeResolver revalidates hex per-field and the server
                // watermark entitlement gates rendering.
                theme = ReporterThemeOptions(
                    background = opts.takeIfHasString("themeBackground"),
                    surface = opts.takeIfHasString("themeSurface"),
                    border = opts.takeIfHasString("themeBorder"),
                    text = opts.takeIfHasString("themeText"),
                    textMuted = opts.takeIfHasString("themeTextMuted"),
                    accent = opts.takeIfHasString("themeAccent"),
                    accentForeground = opts.takeIfHasString("themeAccentForeground"),
                    destructive = opts.takeIfHasString("themeDestructive"),
                ).takeIf { it != ReporterThemeOptions() },
                // Session Vitals (spec 2026-09-06): three flat ConfigOpts
                // fields (RN codegen cannot express the nested `vitals`
                // object; `extractBridgeConfig` flattens). Present fields
                // only — absent keeps VitalsConfig's own defaults, which is
                // what "no host opinion" has to mean: null `enabled` follows
                // the dashboard toggle, null `sampleRate` follows the server
                // rate.
                vitals = dev.everframe.config.VitalsConfig(
                    enabled = opts.takeIfHasBoolean("vitalsEnabled"),
                    sampleRate = opts.takeIfHasDouble("vitalsSampleRate"),
                    captureSourceQuery = opts.takeIfHasBoolean("vitalsCaptureSourceQuery") ?: false,
                ),
            )
            // Codex round-6, H1 — IDEMPOTENT configure, decided against the INSTALLED config.
            //
            // A `Everframe.start(...)` supersedes the running SDK: the outgoing controller's
            // shutdown detaches every integration it had announced, so a Provider that merely
            // REMOUNTS with the same config used to kill every live player registration for
            // nothing. Nothing about the SDK's state differs after a start with an identical
            // config, so the cheapest correct answer is not to start at all.
            //
            // Round-5 answered that question from a CACHED snapshot of the last options this
            // bridge had started with. A cache can disagree with reality. Two overlapping
            // configures (A then B) can interleave so the cache ends up saying A while the
            // singleton runs B — and a native host that calls `Everframe.start(configB)` between
            // two bridge configures of A reproduces it with no concurrency at all: the second
            // A matches the stale cached A, skips, and leaves B installed under a JS host that
            // believes it configured A.
            //
            // So compare against what is actually INSTALLED. `EverframeConfig` is a data class,
            // so `==` is structural over every field a start would write, which makes the
            // comparison exhaustive by construction — a new config field can never be forgotten
            // here the way a hand-maintained key list could be. The two extra terms:
            //   • `captureGate` — a killed SDK must be restarted even by an identical config,
            //     or the host is left with a dead SDK and no way to revive it.
            //   • `attachPinUi` — the one bridge option that lands in module state instead of
            //     in `EverframeConfig`, so config equality alone cannot see it change.
            if (Everframe.captureGate &&
                Everframe.currentConfig == config &&
                companionAttachPinUi == attachPinUi
            ) {
                android.util.Log.d(
                    "Everframe.rn",
                    "configure: SDK already running this exact config — skipping start()",
                )
                installPresenterResolverIfNeeded()
                completed = true
                return@txGuardSurface
            }

            // Stash the attach-PIN UI mode for startCompanion() to read (spec 2026-08-19). It
            // is written only on the start path: the skip path above has already established
            // that the stashed value equals the parsed one.
            companionAttachPinUi = attachPinUi

            // Pass the live Activity: configure() runs from JS long after
            // MainActivity's onCreate, so without it the tap adapter's
            // Window.Callback wrapper is never installed on the current screen
            // and the session ships zero tap crumbs (field bug 2026-07-10).
            Everframe.start(reactContext.applicationContext, config, reactContext.currentActivity)

            // Codex round-5, G1 — the registry is NOT renewed here any more. The live players
            // this start just orphaned are re-registered from JS instead: `mount()` bumps the
            // configure epoch right after this call returns, every vitals hook has that epoch in
            // its effect deps, and each effect's cleanup+re-run detaches the dead token and
            // tracks a fresh one against the SDK that is now current. `renewAll()` could race
            // the runtime's deferred-registration drain and detach the very replacement it had
            // installed, and it only ever covered THIS module instance's registry.

            // Wire TXReporterPresenter as the resolver for
            // Everframe.shared.report.open(). Mirrors iOS TXReporterPresenter
            // .installResolver(). Reflective lookup keeps :sdk-react-native
            // from a hard dependency on :everframe-reporter-ui (which the host
            // app pulls in via its app build.gradle).
            installPresenterResolverIfNeeded()
            completed = true
        }
        return completed
    }

    // ---------------- openReporter ----------------

    /**
     * Opens the native TXReporterPresenter modal. Resolves with the user's
     * outcome. Result shape matches iOS — JS facade casts to ReporterResult.
     *
     *   { status: "submitted", reportId: "<uuid>" }
     *   { status: "queued",    reportId: "<uuid>" }
     *   { status: "cancelled" }
     */
    @ReactMethod
    override fun openReporter(promise: Promise) {
        if (!Everframe.captureGate) {
            promise.reject(REJECT_CAPTURE_DISABLED, "Everframe not started (captureGate=false). Call configure() first.")
            return
        }
        // ReporterResolverInstaller tracks the active Activity via its own
        // ActivityRegistry — we don't pass currentActivity through. But we
        // ensure the resolver is installed so report.open() doesn't throw.
        installPresenterResolverIfNeeded()

        MainScope().launch {
            try {
                val result: ReportResult = withContext(Dispatchers.Main) {
                    Everframe.report.open()
                }
                val dict = Arguments.createMap().apply {
                    when (result) {
                        is ReportResult.Submitted -> {
                            putString("status", "submitted")
                            putString("reportId", result.reportId.toString())
                        }
                        is ReportResult.Queued -> {
                            putString("status", "queued")
                            putString("reportId", result.reportId.toString())
                        }
                        is ReportResult.Cancelled -> {
                            putString("status", "cancelled")
                            putString("reason", result.reason)
                        }
                    }
                }
                promise.resolve(dict)
            } catch (t: Throwable) {
                promise.reject(REJECT_OPEN_REPORTER_FAILED, t.message, t)
            }
        }
    }

