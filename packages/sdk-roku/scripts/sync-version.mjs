// Single source of truth for the SDK version (same pattern as sdk-web's
// sync-version): reads package.json "version" and rewrites
//   - library/components/Everframe/lib/ef_version.brs (envelope sdk.version)
//   - library/manifest major_version / minor_version / build_version
// Wired as `prebuild`, so `pnpm build` can never ship a stale version.
// Idempotent: rerunning without a package.json change rewrites identical bytes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(path.join(pkg, 'package.json'), 'utf8'));
const m = /^(\d+)\.(\d+)\.(\d+)(-[A-Za-z0-9.-]+)?$/.exec(String(version));
if (!m) {
  console.error(`error: '${version}' is not a valid SemVer string`);
  process.exit(1);
}
const [, major, minor, build] = m;

writeFileSync(
  path.join(pkg, 'library/components/Everframe/lib/ef_version.brs'),
  `' SPDX-License-Identifier: MIT
' SPDX-FileCopyrightText: 2026 ScriptX
' AUTO-GENERATED by scripts/sync-version.mjs from package.json "version". Do not edit.
function EF_VERSION() as string
    return "${version}"
end function
`,
);

const manifestPath = path.join(pkg, 'library/manifest');
let manifest = readFileSync(manifestPath, 'utf8');
for (const [key, value] of [['major_version', major], ['minor_version', minor], ['build_version', build]]) {
  const re = new RegExp(`^${key}=.*$`, 'm');
  if (!re.test(manifest)) {
    console.error(`error: ${key} missing from ${manifestPath}`);
    process.exit(1);
  }
  manifest = manifest.replace(re, `${key}=${value}`);
}
writeFileSync(manifestPath, manifest);
console.log(`[sync-version] EF_VERSION = ${version}`);
