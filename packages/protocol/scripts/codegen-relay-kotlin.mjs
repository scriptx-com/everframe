// PROTO-03 Kotlin codegen for the relay control-frame schema. Generates
// `packages/sdk-android/android/traceitx-protocol/src/main/kotlin/com/traceitx/protocol/generated/Relay.kt`
// from `packages/protocol/schemas-json/relay.v1.schema.json`.
//
// Why a custom emitter instead of `npx quicktype@23` (the pattern used by
// codegen-kotlin.sh for the envelope schema)? quicktype@23's Kotlin backend
// crashes with `Error: s.codePointAt is not a function.` on this schema
// (upstream bug). Custom emitter keeps the same drift-gate contract: single
// Zod source of truth → JSON Schema → generated Kotlin, with
// `pnpm -w codegen && git diff --exit-code` as the gate.
//
// Shape it emits:
//   - `@Serializable @JsonClassDiscriminator("type") sealed class RelayMessage`
//   - Per branch: `@Serializable @SerialName("pair.created") data class PairCreated(...) : RelayMessage()`

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..', '..');
const schemaPath = path.join(
  repoRoot,
  'packages/protocol/schemas-json/relay.v1.schema.json'
);
const outPath = path.join(
  repoRoot,
  'packages/sdk-android/android/traceitx-protocol/src/main/kotlin/com/traceitx/protocol/generated/Relay.kt'
);

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
if (!Array.isArray(schema.oneOf)) {
  console.error('relay schema is not oneOf at root; emitter aborts');
  process.exit(1);
}

const HEADER = `// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: 2026 ScriptX
// AUTOGENERATED by packages/protocol/scripts/codegen-relay-kotlin.mjs — DO NOT EDIT.
// To regenerate: pnpm -w codegen
// CI gate: pnpm -w codegen && git diff --exit-code packages/sdk-android/android/traceitx-protocol/
//
// Custom emitter (not quicktype): quicktype@23's Kotlin backend crashes on
// this schema (upstream bug). See header of codegen-relay-kotlin.mjs.

package com.traceitx.protocol.generated

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonClassDiscriminator
`;

const snake_to_camel = (s) =>
  s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

// Render a Kotlin type for a JSON-Schema field. For inline nested objects /
// arrays of objects we emit a fresh nominal data class into `extraTypes`.
function kotlinType(prop, ownerName, fieldName, extraTypes) {
  if (prop.type === 'string') return 'String';
  if (prop.type === 'boolean') return 'Boolean';
  if (prop.type === 'integer') return 'Long';
  if (prop.type === 'number') return 'Double';
  if (prop.enum) return 'String';
  if (prop.type === 'array') {
    if (Array.isArray(prop.prefixItems)) {
      const inner = kotlinType(
        prop.prefixItems[0],
        ownerName,
        fieldName,
        extraTypes
      );
      return `List<${inner}>`;
    }
    const singular = fieldName.endsWith('s')
      ? fieldName.slice(0, -1)
      : fieldName + 'Item';
    const inner = kotlinType(prop.items, ownerName, singular, extraTypes);
    return `List<${inner}>`;
  }
  if (prop.type === 'object') {
    const typeName = ownerName + pascal(snake_to_camel(fieldName));
    emitDataClass(typeName, prop, extraTypes);
    return typeName;
  }
  if (prop.oneOf) {
    const typeName = ownerName + pascal(snake_to_camel(fieldName));
    emitInlineSealed(typeName, prop, extraTypes);
    return typeName;
  }
  throw new Error(
    `unhandled type for ${ownerName}.${fieldName}: ${JSON.stringify(prop)}`
  );
}

function emitDataClass(name, objSchema, extraTypes, skipTypeField = false) {
  if (extraTypes.has(name)) return;
  extraTypes.set(name, '');
  const required = new Set(objSchema.required || []);
  const props = objSchema.properties || {};
  const fieldNames = Object.keys(props).sort();

  const params = fieldNames
    .filter((f) => !(skipTypeField && f === 'type'))
    .map((f) => {
      const p = props[f];
      const kName = snake_to_camel(f);
      const t = kotlinType(p, name, f, extraTypes);
      const optional = !required.has(f);
      const annot = kName === f ? '' : `@SerialName("${f}") `;
      const decl = `${annot}val ${kName}: ${t}${optional ? '? = null' : ''}`;
      return `    ${decl}`;
    });

  const code =
    `@Serializable\n` +
    `data class ${name}(\n` +
    params.join(',\n') +
    `\n)\n`;

  extraTypes.set(name, code);
}

function emitInlineSealed(name, prop, extraTypes) {
  if (extraTypes.has(name)) return;
  extraTypes.set(name, '');
  const branches = prop.oneOf.map((b) => {
    const kind = b.properties.kind.const;
    const branchName = name + pascal(snake_to_camel(kind));
    emitDataClassSubclass(branchName, b, name, 'kind', kind, extraTypes);
    return { kind, branchName };
  });

  const code =
    `@Serializable\n` +
    `@JsonClassDiscriminator("kind")\n` +
    `sealed class ${name}\n` +
    branches
      .map((b) => `// branch ${b.kind} → ${b.branchName}`)
      .join('\n') +
    '\n';
  extraTypes.set(name, code);
}

function emitDataClassSubclass(
  name,
  objSchema,
  parentName,
  discField,
  discValue,
  extraTypes
) {
  if (extraTypes.has(name)) return;
  extraTypes.set(name, '');
  const required = new Set(objSchema.required || []);
  const props = objSchema.properties || {};
  const fieldNames = Object.keys(props)
    .filter((f) => f !== discField)
    .sort();

  const params = fieldNames.map((f) => {
    const p = props[f];
    const kName = snake_to_camel(f);
    const t = kotlinType(p, name, f, extraTypes);
    const optional = !required.has(f);
    const annot = kName === f ? '' : `@SerialName("${f}") `;
    const decl = `${annot}val ${kName}: ${t}${optional ? '? = null' : ''}`;
    return `    ${decl}`;
  });

  const code =
    `@Serializable\n` +
    `@SerialName("${discValue}")\n` +
    (params.length === 0
      ? `data class ${name}(val _placeholder: Boolean = true) : ${parentName}()\n`
      : `data class ${name}(\n` + params.join(',\n') + `\n) : ${parentName}()\n`);

  extraTypes.set(name, code);
}

// --- main emit ---------------------------------------------------------

const extraTypes = new Map();

const branches = schema.oneOf
  .map((b) => {
    if (!b.$id) throw new Error('branch missing $id');
    const branchName = b.$id;
    emitDataClassSubclass(
      branchName,
      b,
      'RelayMessage',
      'type',
      b.properties.type.const,
      extraTypes
    );
    return { branchName, disc: b.properties.type.const };
  })
  .sort((a, b) => a.branchName.localeCompare(b.branchName));

const sealedBlock =
  `@Serializable\n` +
  `@JsonClassDiscriminator("type")\n` +
  `sealed class RelayMessage\n`;

const sortedExtras = [...extraTypes.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([, code]) => code)
  .join('\n');

const final = HEADER + '\n' + sealedBlock + '\n' + sortedExtras;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, final);
console.log(`[codegen-relay-kotlin] wrote ${outPath}`);
