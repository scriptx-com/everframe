// PROTO-03 Swift codegen for the relay control-frame schema. Generates
// `packages/sdk-ios/Sources/EverframeProtocol/Relay.swift` from
// `packages/protocol/schemas-json/relay.v1.schema.json`.
//
// Why a custom emitter instead of `npx quicktype@23` (the pattern used by
// codegen-swift.sh for the envelope schema)?
//
//   - quicktype@23 crashes with `Error: s.codePointAt is not a function.` on
//     this schema's Kotlin backend (open issue against quicktype). On Swift
//     the codegen completes but FLATTENS the `oneOf` of discriminated objects
//     into a single `struct RelayMessage` with every union member's fields as
//     optionals — exactly the shape RESEARCH.md §Pitfall 10 warned about.
//     That violates the plan's hard requirement (`enum RelayMessage` with
//     associated values) and would defeat the type-safety the source-of-truth
//     Zod schema gives us.
//
// The drift gate (`pnpm -w codegen && git diff --exit-code`) and the single
// Zod source of truth are unchanged. Only the language-emit step is custom.
//
// Shape it emits:
//   - One Swift struct per branch (`PairCreated`, `PairBonded`, ...)
//   - Top-level `public enum RelayMessage: Codable { case pairCreated(PairCreated); ... }`
//     with a custom `init(from:)` that switches on the `type` discriminator
//     and an `encode(to:)` that delegates to the wrapped struct.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..', '..');
const schemaPath = path.join(
  repoRoot,
  'packages/protocol/schemas-json/relay.v1.schema.json'
);
const outPath = path.join(
  repoRoot,
  'packages/sdk-ios/Sources/EverframeProtocol/Relay.swift'
);

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
if (!Array.isArray(schema.oneOf)) {
  console.error('relay schema is not oneOf at root; emitter aborts');
  process.exit(1);
}

// --- helpers -----------------------------------------------------------

const HEADER = `// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: 2026 ScriptX
// AUTOGENERATED by packages/protocol/scripts/codegen-relay-swift.mjs — DO NOT EDIT.
// To regenerate: pnpm -w codegen
// CI gate: pnpm -w codegen && git diff --exit-code packages/sdk-ios/Sources/EverframeProtocol/
//
// Custom emitter (not quicktype): quicktype@23 flattens oneOf-with-const into
// a single struct, which violates the SPEC requirement for an enum with
// associated values. See header of codegen-relay-swift.mjs for details.

import Foundation
`;

const snake_to_camel = (s) =>
  s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());

const dot_to_pascal = (s) =>
  s
    .split('.')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const prefixed = (name) => name.startsWith('Everframe') ? name : `Everframe${name}`;
const camel = (s) => s.charAt(0).toLowerCase() + s.slice(1);

// Render a Swift type for a JSON-Schema field. For inline nested objects /
// arrays of objects we emit a fresh nominal type into `extraTypes`.
function swiftType(prop, ownerName, fieldName, extraTypes) {
  if (prop.const !== undefined && prop.type === 'string') {
    return 'String';
  }
  if (prop.const === true && prop.type === 'boolean') {
    return 'Bool';
  }
  if (prop.type === 'string') return 'String';
  if (prop.type === 'boolean') return 'Bool';
  if (prop.type === 'integer') return 'Int';
  if (prop.type === 'number') return 'Double';
  if (prop.enum) return 'String';
  if (prop.type === 'array') {
    // Tuple: prefixItems → fixed-length [Double] array (Swift has no tuple Codable).
    if (Array.isArray(prop.prefixItems)) {
      const inner = prop.prefixItems[0];
      return `[${swiftType(inner, ownerName, fieldName, extraTypes)}]`;
    }
    // For array items, drop a trailing 's' on the field name (annotations →
    // Annotation) so the emitted type is `ReportSubmitAnnotation`, not
    // `ReportSubmitAnnotationsItem`. Falls back to appending 'Item' when the
    // field is already singular (e.g. `points`).
    const singular = fieldName.endsWith('s')
      ? fieldName.slice(0, -1)
      : fieldName + 'Item';
    const inner = swiftType(prop.items, ownerName, singular, extraTypes);
    return `[${inner}]`;
  }
  if (prop.type === 'object') {
    const typeName = ownerName + pascal(snake_to_camel(fieldName));
    emitStruct(typeName, prop, extraTypes);
    return typeName;
  }
  if (prop.oneOf) {
    // Inline oneOf union (e.g. annotation: stroke | blur). Emit a nested enum.
    const typeName = ownerName + pascal(snake_to_camel(fieldName)) + 'Item';
    emitInlineOneOf(typeName, prop, extraTypes);
    return typeName;
  }
  throw new Error(
    `unhandled type for ${ownerName}.${fieldName}: ${JSON.stringify(prop)}`
  );
}

function emitStruct(name, objSchema, extraTypes) {
  if (extraTypes.has(name)) return; // already emitted (dedupe by name)
  extraTypes.set(name, ''); // placeholder so recursive nested types don't loop
  const required = new Set(objSchema.required || []);
  const props = objSchema.properties || {};
  const fieldOrder = Object.keys(props).sort();

  const fieldDecls = [];
  const codingKeys = [];
  for (const f of fieldOrder) {
    const p = props[f];
    const swiftName = snake_to_camel(f);
    const optional = !required.has(f);
    const t = swiftType(p, name, f, extraTypes) + (optional ? '?' : '');
    fieldDecls.push(`    public let ${swiftName}: ${t}`);
    codingKeys.push(
      swiftName === f
        ? `        case ${swiftName}`
        : `        case ${swiftName} = "${f}"`
    );
  }

  const code = [
    `public struct ${name}: Codable, Equatable {`,
    ...fieldDecls,
    '',
    '    public enum CodingKeys: String, CodingKey {',
    ...codingKeys,
    '    }',
    '',
    `    public init(${fieldOrder
      .map((f) => {
        const p = props[f];
        const swiftName = snake_to_camel(f);
        const t = swiftType(p, name, f, extraTypes);
        const optional = !required.has(f);
        return `${swiftName}: ${t}${optional ? '? = nil' : ''}`;
      })
      .join(', ')}) {`,
    ...fieldOrder.map((f) => {
      const swiftName = snake_to_camel(f);
      return `        self.${swiftName} = ${swiftName}`;
    }),
    '    }',
    '}',
    '',
  ].join('\n');

  extraTypes.set(name, code);
}

function emitInlineOneOf(name, prop, extraTypes) {
  if (extraTypes.has(name)) return;
  extraTypes.set(name, '');
  // Each branch has a `kind` const discriminator. Emit a struct per branch
  // and a Swift enum with associated values.
  const branches = prop.oneOf.map((b) => {
    const kind = b.properties.kind.const;
    const branchName = name + pascal(snake_to_camel(kind));
    emitStruct(branchName, b, extraTypes);
    return { kind, branchName };
  });

  const cases = branches
    .map((b) => `    case ${camel(snake_to_camel(b.kind))}(${b.branchName})`)
    .join('\n');

  const decodeCases = branches
    .map(
      (b) =>
        `        case "${b.kind}": self = .${camel(snake_to_camel(b.kind))}(try ${b.branchName}(from: decoder))`
    )
    .join('\n');

  const encodeCases = branches
    .map(
      (b) =>
        `        case .${camel(snake_to_camel(b.kind))}(let v): try v.encode(to: encoder)`
    )
    .join('\n');

  const code = `public enum ${name}: Codable, Equatable {
${cases}

    private enum DiscKey: String, CodingKey { case kind }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: DiscKey.self)
        let kind = try c.decode(String.self, forKey: .kind)
        switch kind {
${decodeCases}
        default:
            throw DecodingError.dataCorruptedError(
                forKey: .kind, in: c,
                debugDescription: "Unknown ${name} kind '\\(kind)'"
            )
        }
    }

    public func encode(to encoder: Encoder) throws {
        switch self {
${encodeCases}
        }
    }
}
`;
  extraTypes.set(name, code);
}

// --- main emit ---------------------------------------------------------

const extraTypes = new Map(); // name → emitted Swift code

const branches = schema.oneOf.map((b) => {
  if (!b.$id) {
    throw new Error('branch missing $id: ' + JSON.stringify(b).slice(0, 80));
  }
  const branchName = prefixed(b.$id);
  emitStruct(branchName, b, extraTypes);
  // Pull the const value of the `type` field as the wire discriminator.
  const disc = b.properties.type.const;
  return { branchName, disc, caseName: camel(dot_to_pascal(disc)) };
}).sort((a, b) => a.branchName.localeCompare(b.branchName));

const enumCases = branches
  .map((b) => `    case ${b.caseName}(${b.branchName})`)
  .join('\n');

const decodeCases = branches
  .map(
    (b) =>
      `        case "${b.disc}": self = .${b.caseName}(try ${b.branchName}(from: decoder))`
  )
  .join('\n');

const encodeCases = branches
  .map(
    (b) =>
      `        case .${b.caseName}(let v): try v.encode(to: encoder)`
  )
  .join('\n');

const enumBlock = `public enum EverframeRelayMessage: Codable, Equatable {
${enumCases}

    private enum DiscKey: String, CodingKey { case type }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: DiscKey.self)
        let type = try c.decode(String.self, forKey: .type)
        switch type {
${decodeCases}
        default:
            throw DecodingError.dataCorruptedError(
                forKey: .type, in: c,
                debugDescription: "Unknown EverframeRelayMessage type '\\(type)'"
            )
        }
    }

    public func encode(to encoder: Encoder) throws {
        switch self {
${encodeCases}
        }
    }
}
`;

// Sort extraTypes by name for deterministic output.
const sortedExtras = [...extraTypes.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([, code]) => code)
  .join('\n');

const final = HEADER + '\n' + sortedExtras + '\n' + enumBlock;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, final);
console.log(`[codegen-relay-swift] wrote ${outPath}`);
