# PROTO-01 Swift codegen — generates packages/sdk-ios/Sources/TraceItXProtocol/Generated.swift
# from packages/protocol/schemas-json/envelope.v1.schema.json via quicktype.
#
# Drift gate: CI runs `pnpm -w codegen && git diff --exit-code packages/sdk-ios/Sources/TraceItXProtocol/`.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
SCHEMA_PATH="$REPO_ROOT/packages/protocol/schemas-json/envelope.v1.schema.json"
OUT_PATH="$REPO_ROOT/packages/sdk-ios/Sources/TraceItXProtocol/Generated.swift"

if [[ ! -f "$SCHEMA_PATH" ]]; then
  echo "schema.json missing at $SCHEMA_PATH; run 'pnpm schema:generate' first" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT_PATH")"

# Plan-locked invocation adjusted for quicktype@23 valid flags.
# See the implementation notes for rationale.
npx --yes quicktype@23 \
  --src-lang schema \
  --src "$SCHEMA_PATH" \
  --lang swift \
  --top-level ReportEnvelope \
  --struct-or-class struct \
  --density dense \
  --access-level public \
  --out "$OUT_PATH"

# Prepend the AUTOGENERATED header marker so CI drift detection and humans
# both see provenance at the top of the file.
# REUSE-IgnoreStart
HEADER=$'// SPDX-License-Identifier: MIT\n// SPDX-FileCopyrightText: 2026 ScriptX\n// AUTOGENERATED by packages/protocol/scripts/codegen-swift.sh \xe2\x80\x94 DO NOT EDIT.\n// To regenerate: pnpm -w codegen\n// CI gate: pnpm -w codegen && git diff --exit-code packages/sdk-ios/Sources/TraceItXProtocol/\n\n'
# REUSE-IgnoreEnd
BODY="$(cat "$OUT_PATH")"
printf '%s%s\n' "$HEADER" "$BODY" > "$OUT_PATH"
