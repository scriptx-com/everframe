// VTREE-01 Kotlin codegen for the native session-replay timeline schema.
// Generates
// `packages/sdk-android/android/traceitx-protocol/src/main/kotlin/com/traceitx/protocol/generated/VTree.kt`
// from `packages/protocol/schemas-json/vtree.v1.schema.json`.
//
// Why a custom emitter instead of `npx quicktype@23` (codegen-kotlin.sh)?
//
//   - EMPIRICALLY PROVEN (21-RESEARCH.md §"Empirical test results", Findings
//     B+C): the plain quicktype path DUPLICATES the recursive VNode (Snapshot +
//     Node instead of one VNode) and FLATTENS the VOp discriminated union into
//     an all-optional data class. Both break the traceitx-vtree-v1 contract.
//
//   - Modeled on codegen-relay-kotlin.mjs, but the vtree schema ROOT is the
//     `VTreeTimeline` OBJECT (not a top-level `oneOf`):
//       * the recursive VNode is anonymized by z.toJSONSchema to `$defs.__schema0`
//         and referenced via `{"$ref":"#/$defs/__schema0"}` (Finding A). We
//         resolve that ONE ref to a single `@Serializable data class VNode`.
//       * the VOp `oneOf` lives at `frames.items.properties.ops.items`; each
//         branch carries an `$id` (VOpSet/VOpAdd/VOpRemove) and an `op` const
//         discriminator. We emit `@JsonClassDiscriminator("op") sealed class VOp`
//         with three `@SerialName(...) data class ... : VOp()` subclasses.
//
// Drift gate (`pnpm codegen && git diff --exit-code`) + single Zod source of
// truth unchanged. Only the language-emit step is custom.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..', '..');
const schemaPath = path.join(
  repoRoot,
  'packages/protocol/schemas-json/vtree.v1.schema.json'
);
const outPath = path.join(
  repoRoot,
  'packages/sdk-android/android/traceitx-protocol/src/main/kotlin/com/traceitx/protocol/generated/VTree.kt'
);

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
if (schema.type !== 'object' || !schema.properties) {
  console.error('vtree schema root is not an object; emitter aborts');
  process.exit(1);
}

// The generator re-points the recursive `$ref` from `#/$defs/__schema0` to the
// def's `$id` ('VNode') so the schema resolves under ajv across nested `$id`
// scopes; the emitter resolves it by `$id` and looks the def up by its stable
// `$defs` key.
const VNODE_REF = 'VNode';
const VNODE_NAME = 'VNode';
const vnodeDefKey = '__schema0';
if (!schema.$defs || !schema.$defs[vnodeDefKey]) {
  console.error(`vtree schema missing recursive $defs.${vnodeDefKey}; aborts`);
  process.exit(1);
}

const HEADER = `// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: 2026 ScriptX
// AUTOGENERATED by packages/protocol/scripts/codegen-vtree-kotlin.mjs — DO NOT EDIT.
// To regenerate: pnpm -w codegen
// CI gate: pnpm -w codegen && git diff --exit-code packages/sdk-android/android/traceitx-protocol/
//
// Custom emitter (not quicktype): the plain quicktype path duplicates the
// recursive VNode (Snapshot + Node) and flattens the VOp discriminated union
// into an all-optional data class — empirically proven (21-RESEARCH.md). This
// emitter resolves the recursive ref to a single VNode declaration and emits
// VOp as a sealed class. See header of codegen-vtree-kotlin.mjs.

package dev.everframe.protocol.generated

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonClassDiscriminator
`;

const snake_to_camel = (s) =>
  s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

/**
 * True for a JSON Schema object used as an open-ended MAP: `additionalProperties`
 * is a schema (not `false`/absent). `z.record()` also emits `propertyNames`, but
 * that is not required for the shape to be a map, so it is not tested here.
 */
function isMapSchema(prop) {
  const ap = prop.additionalProperties;
  return !!ap && typeof ap === 'object';
}

function kotlinType(prop, ownerName, fieldName, extraTypes) {
  if (prop.$ref === VNODE_REF) {
    return VNODE_NAME;
  }
  if (prop.type === 'string') return 'String';
  if (prop.type === 'boolean') return 'Boolean';
  if (prop.type === 'integer') return 'Long';
  if (prop.type === 'number') return 'Double';
  if (prop.enum) return 'String';
  if (prop.type === 'array') {
    if (Array.isArray(prop.prefixItems)) {
      const inner = kotlinType(
        prop.prefixItems[0],
        ownerName,
        fieldName,
        extraTypes
      );
      return `List<${inner}>`;
    }
    const items = prop.items;
    if (items && items.$ref === VNODE_REF) {
      return `List<${VNODE_NAME}>`;
    }
    if (items && items.$id) {
      if (items.oneOf) {
        emitInlineSealed(items.$id, items, extraTypes);
      } else if (items.type === 'object') {
        emitDataClass(items.$id, items, extraTypes);
      }
      return `List<${items.$id}>`;
    }
    const singular = fieldName.endsWith('s')
      ? fieldName.slice(0, -1)
      : fieldName + 'Item';
    const inner = kotlinType(items, ownerName, singular, extraTypes);
    return `List<${inner}>`;
  }
  if (prop.type === 'object' && !prop.properties && isMapSchema(prop)) {
    // A MAP, not a record: `z.record(z.string(), X)` emits an object with NO
    // `properties` and an object-valued `additionalProperties`. Without this
    // branch the generic object path below built a data class out of the
    // (empty) `properties` — an EMPTY data class with no storage, so the SDK
    // could not carry the map's contents at all, and it compiled clean.
    const value = prop.additionalProperties;
    const valueType = value.$id || ownerName + pascal(snake_to_camel(fieldName)) + 'Value';
    if (value.type === 'object') emitDataClass(valueType, value, extraTypes);
    return `Map<String, ${valueType}>`;
  }
  if (prop.type === 'object') {
    // The `frame` rect object ({x,y,w,h}) appears inline under both VNode and
    // VOpSet. Emit it ONCE as a shared `VRect` so it isn't duplicated as
    // VNodeFrame + VOpSetFrame.
    const typeName =
      fieldName === 'frame' ? 'VRect' : ownerName + pascal(snake_to_camel(fieldName));
    emitDataClass(typeName, prop, extraTypes);
    return typeName;
  }
  if (prop.oneOf) {
    const typeName = prop.$id || ownerName + pascal(snake_to_camel(fieldName));
    emitInlineSealed(typeName, prop, extraTypes);
    return typeName;
  }
  throw new Error(
    `unhandled type for ${ownerName}.${fieldName}: ${JSON.stringify(prop)}`
  );
}

function emitDataClass(name, objSchema, extraTypes) {
  if (extraTypes.has(name)) return;
  extraTypes.set(name, '');
  const required = new Set(objSchema.required || []);
  const props = objSchema.properties || {};
  const fieldNames = Object.keys(props).sort();

  const params = fieldNames.map((f) => {
    const p = props[f];
    const kName = snake_to_camel(f);
    const t = kotlinType(p, name, f, extraTypes);
    const optional = !required.has(f);
    const annot = kName === f ? '' : `@SerialName("${f}") `;
    const decl = `${annot}val ${kName}: ${t}${optional ? '? = null' : ''}`;
    return `    ${decl}`;
  });

  const code =
    `@Serializable\n` +
    `data class ${name}(\n` +
    params.join(',\n') +
    `\n)\n`;

  extraTypes.set(name, code);
}

// oneOf-with-`op`-const → @JsonClassDiscriminator("op") sealed class + one
// @SerialName(...) data class subclass per branch.
function emitInlineSealed(name, prop, extraTypes) {
  if (extraTypes.has(name)) return;
  extraTypes.set(name, '');
  const branches = prop.oneOf.map((b) => {
    const disc = b.properties.op.const;
    const branchName = b.$id || name + pascal(snake_to_camel(disc));
    emitDataClassSubclass(branchName, b, name, 'op', disc, extraTypes);
    return { disc, branchName };
  });

  const code =
    `@Serializable\n` +
    `@JsonClassDiscriminator("op")\n` +
    `sealed class ${name}\n` +
    branches
      .map((b) => `// branch ${b.disc} → ${b.branchName}`)
      .join('\n') +
    '\n';
  extraTypes.set(name, code);
}

function emitDataClassSubclass(
  name,
  objSchema,
  parentName,
  discField,
  discValue,
  extraTypes
) {
  if (extraTypes.has(name)) return;
  extraTypes.set(name, '');
  const required = new Set(objSchema.required || []);
  const props = objSchema.properties || {};
  const fieldNames = Object.keys(props)
    .filter((f) => f !== discField)
    .sort();

  const params = fieldNames.map((f) => {
    const p = props[f];
    const kName = snake_to_camel(f);
    const t = kotlinType(p, name, f, extraTypes);
    const optional = !required.has(f);
    const annot = kName === f ? '' : `@SerialName("${f}") `;
    const decl = `${annot}val ${kName}: ${t}${optional ? '? = null' : ''}`;
    return `    ${decl}`;
  });

  const code =
    `@Serializable\n` +
    `@SerialName("${discValue}")\n` +
    (params.length === 0
      ? `data class ${name}(val _placeholder: Boolean = true) : ${parentName}()\n`
      : `data class ${name}(\n` + params.join(',\n') + `\n) : ${parentName}()\n`);

  extraTypes.set(name, code);
}

// --- main emit ---------------------------------------------------------

const extraTypes = new Map();

// 1. Resolve the recursive node ONCE under the fixed name `VNode` (Finding A).
emitDataClass(VNODE_NAME, schema.$defs[vnodeDefKey], extraTypes);

// 2. Emit the root VTreeTimeline data class; frames/ops/viewport recurse
//    through kotlinType (→ VFrame, VOp, VOpSet/VOpAdd/VOpRemove, nested viewport).
emitDataClass('VTreeTimeline', schema, extraTypes);

const sortedExtras = [...extraTypes.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([, code]) => code)
  .join('\n');

const final = HEADER + '\n' + sortedExtras;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, final);
console.log(`[codegen-vtree-kotlin] wrote ${outPath}`);
