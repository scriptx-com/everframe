// VTREE-01 Swift codegen for the native session-replay timeline schema.
// Generates `packages/sdk-ios/Sources/TraceItXProtocol/VTree.swift` from
// `packages/protocol/schemas-json/vtree.v1.schema.json`.
//
// Why a custom emitter instead of `npx quicktype@23` (codegen-swift.sh)?
//
//   - EMPIRICALLY PROVEN (21-RESEARCH.md §"Empirical test results", Findings
//     B+C): the plain quicktype envelope path DUPLICATES the recursive VNode
//     (emits `Snapshot` + `Node` instead of one `VNode`) and FLATTENS the VOp
//     discriminated union into a single all-optional struct. Both break the
//     traceitx-vtree-v1 contract for Phases 22/23/25.
//
//   - This emitter is modeled on codegen-relay-swift.mjs but the vtree schema
//     ROOT is the `VTreeTimeline` OBJECT (not a top-level `oneOf` like relay):
//       * the recursive VNode is anonymized by z.toJSONSchema to a `$defs`
//         entry keyed `__schema0` and referenced via `{"$ref":"#/$defs/__schema0"}`
//         (Finding A). We RESOLVE that one ref to a single named `VNode` struct.
//       * the VOp `oneOf` lives at `frames.items.properties.ops.items`; each
//         branch carries an `$id` (VOpSet/VOpAdd/VOpRemove) and an `op` const
//         discriminator. We emit a Swift `enum VOp` with associated values
//         (reusing the relay enum-emit shape, DiscKey → `op`).
//
// The drift gate (`pnpm codegen && git diff --exit-code`) and the single Zod
// source of truth are unchanged. Only the language-emit step is custom.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..', '..');
const schemaPath = path.join(
  repoRoot,
  'packages/protocol/schemas-json/vtree.v1.schema.json'
);
const outPath = path.join(
  repoRoot,
  'packages/sdk-ios/Sources/TraceItXProtocol/VTree.swift'
);

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
if (schema.type !== 'object' || !schema.properties) {
  console.error('vtree schema root is not an object; emitter aborts');
  process.exit(1);
}

// The recursive VNode is anonymized to a single $defs entry (`$defs.__schema0`).
// The generator re-points the recursive `$ref` from the JSON-pointer
// `#/$defs/__schema0` to the def's `$id` ('VNode') so the schema resolves under
// ajv across nested `$id` scopes (the VOpAdd scope can't resolve a root-relative
// pointer). The emitter resolves that same ref by `$id` and looks the def up by
// its stable `$defs` key.
const VNODE_REF = 'VNode';
const VNODE_NAME = 'VNode';
const vnodeDefKey = '__schema0';
if (!schema.$defs || !schema.$defs[vnodeDefKey]) {
  console.error(`vtree schema missing recursive $defs.${vnodeDefKey}; aborts`);
  process.exit(1);
}

// --- helpers -----------------------------------------------------------

const HEADER = `// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: 2026 ScriptX
// AUTOGENERATED by packages/protocol/scripts/codegen-vtree-swift.mjs — DO NOT EDIT.
// To regenerate: pnpm -w codegen
// CI gate: pnpm -w codegen && git diff --exit-code packages/sdk-ios/Sources/TraceItXProtocol/
//
// Custom emitter (not quicktype): the plain quicktype path duplicates the
// recursive VNode (Snapshot + Node) and flattens the VOp discriminated union
// into an all-optional struct — empirically proven (21-RESEARCH.md). This
// emitter resolves the recursive ref to a single VNode declaration and emits
// VOp as an enum with associated values. See header of codegen-vtree-swift.mjs.

import Foundation
`;

const snake_to_camel = (s) =>
  s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());

// LOUD invariant doc-comments injected by the emitter (NOT hand-edited into the
// generated file — a hand-edit would fail the next `pnpm codegen && git
// diff --exit-code` drift gate). Keyed by `${StructName}.${swiftFieldName}`.
// The `masked` invariant (`masked ⇒ no text/image`) is enforced ONLY at the
// Zod `.parse()` layer + golden fixture — z.toJSONSchema DROPS the `.refine`
// (22-RESEARCH Pitfall 1) so it is NOT expressible in this generated type. The
// comment is the load-bearing contract surface for native producers + player.
const FIELD_DOC_COMMENTS = {
  'VNode.masked': [
    '    /// INVARIANT (producer-enforced, NOT type-enforced): when `masked == true`',
    '    /// the node MUST carry NO `text` and NO image payload (the screenshot-blackout',
    '    /// PII parity guarantee). The dashboard player (Phase 25) defensively ignores',
    '    /// text on masked nodes. This cannot be checked by the type system or JSON',
    '    /// Schema — z.toJSONSchema drops the Zod .refine that enforces it.',
  ],
};

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

/**
 * True for a JSON Schema object used as an open-ended MAP: `additionalProperties`
 * is a schema (not `false`/absent). Mirrors the Kotlin emitter's helper.
 */
function isMapSchema(prop) {
  const ap = prop.additionalProperties;
  return !!ap && typeof ap === 'object';
}

const camel = (s) => s.charAt(0).toLowerCase() + s.slice(1);

// Render a Swift type for a JSON-Schema field. For inline nested objects /
// arrays of objects we emit a fresh nominal type into `extraTypes`.
function swiftType(prop, ownerName, fieldName, extraTypes) {
  // $ref → the resolved recursive VNode (Finding B fix: NOT a usage-site name).
  if (prop.$ref === VNODE_REF) {
    return VNODE_NAME;
  }
  if (prop.const !== undefined && prop.type === 'string') {
    return 'String';
  }
  if (prop.const === true && prop.type === 'boolean') {
    return 'Bool';
  }
  if (prop.type === 'string') return 'String';
  if (prop.type === 'boolean') return 'Bool';
  if (prop.type === 'integer') return 'Int';
  if (prop.type === 'number') return 'Double';
  if (prop.enum) return 'String';
  if (prop.type === 'array') {
    if (Array.isArray(prop.prefixItems)) {
      const inner = prop.prefixItems[0];
      return `[${swiftType(inner, ownerName, fieldName, extraTypes)}]`;
    }
    const items = prop.items;
    // Named array element: a $ref (→ VNode) or an item carrying its own $id
    // (frames → VFrame, ops → VOp). The singularizer MUST NOT fire here, so we
    // resolve the element name directly rather than synthesizing a usage name.
    if (items && items.$ref === VNODE_REF) {
      return `[${VNODE_NAME}]`;
    }
    if (items && items.$id) {
      if (items.oneOf) {
        emitInlineOneOf(items.$id, items, extraTypes);
      } else if (items.type === 'object') {
        emitStruct(items.$id, items, extraTypes);
      }
      return `[${items.$id}]`;
    }
    const singular = fieldName.endsWith('s')
      ? fieldName.slice(0, -1)
      : fieldName + 'Item';
    const inner = swiftType(items, ownerName, singular, extraTypes);
    return `[${inner}]`;
  }
  if (prop.type === 'object' && !prop.properties && isMapSchema(prop)) {
    // A MAP, not a record — see the Kotlin emitter's twin branch. Without it
    // the generic object path built an EMPTY struct with no storage, so the
    // SDK could not carry the map's contents, and it compiled clean.
    const value = prop.additionalProperties;
    const valueType = value.$id || ownerName + pascal(snake_to_camel(fieldName)) + 'Value';
    if (value.type === 'object') emitStruct(valueType, value, extraTypes);
    return `[String: ${valueType}]`;
  }
  if (prop.type === 'object') {
    // The `frame` rect object ({x,y,w,h}) appears inline under both VNode and
    // VOpSet. Emit it ONCE as a shared `VRect` so it isn't duplicated as
    // VNodeFrame + VOpSetFrame (and so the Pitfall-1 grep for the recursive
    // node stays clean).
    const typeName =
      fieldName === 'frame' ? 'VRect' : ownerName + pascal(snake_to_camel(fieldName));
    emitStruct(typeName, prop, extraTypes);
    return typeName;
  }
  if (prop.oneOf) {
    const typeName = prop.$id || ownerName + pascal(snake_to_camel(fieldName)) + 'Item';
    emitInlineOneOf(typeName, prop, extraTypes);
    return typeName;
  }
  throw new Error(
    `unhandled type for ${ownerName}.${fieldName}: ${JSON.stringify(prop)}`
  );
}

function emitStruct(name, objSchema, extraTypes) {
  if (extraTypes.has(name)) return; // already emitted (dedupe by name)
  extraTypes.set(name, ''); // placeholder so recursive nested types don't loop
  const required = new Set(objSchema.required || []);
  const props = objSchema.properties || {};
  const fieldOrder = Object.keys(props).sort();

  const fieldDecls = [];
  const codingKeys = [];
  for (const f of fieldOrder) {
    const p = props[f];
    const swiftName = snake_to_camel(f);
    const optional = !required.has(f);
    const t = swiftType(p, name, f, extraTypes) + (optional ? '?' : '');
    const docComment = FIELD_DOC_COMMENTS[`${name}.${swiftName}`];
    if (docComment) fieldDecls.push(...docComment);
    fieldDecls.push(`    public let ${swiftName}: ${t}`);
    codingKeys.push(
      swiftName === f
        ? `        case ${swiftName}`
        : `        case ${swiftName} = "${f}"`
    );
  }

  const code = [
    `public struct ${name}: Codable, Equatable {`,
    ...fieldDecls,
    '',
    '    public enum CodingKeys: String, CodingKey {',
    ...codingKeys,
    '    }',
    '',
    `    public init(${fieldOrder
      .map((f) => {
        const p = props[f];
        const swiftName = snake_to_camel(f);
        const t = swiftType(p, name, f, extraTypes);
        const optional = !required.has(f);
        return `${swiftName}: ${t}${optional ? '? = nil' : ''}`;
      })
      .join(', ')}) {`,
    ...fieldOrder.map((f) => {
      const swiftName = snake_to_camel(f);
      return `        self.${swiftName} = ${swiftName}`;
    }),
    '    }',
    '}',
    '',
  ].join('\n');

  extraTypes.set(name, code);
}

// oneOf-with-`op`-const → one struct per branch + a Swift enum with associated
// values. Mirrors the relay RelayMessage enum (DiscKey → `op`).
function emitInlineOneOf(name, prop, extraTypes) {
  if (extraTypes.has(name)) return;
  extraTypes.set(name, '');
  const branches = prop.oneOf
    .map((b) => {
      const disc = b.properties.op.const;
      // Each branch carries its own $id (VOpSet/VOpAdd/VOpRemove).
      const branchName = b.$id || name + pascal(snake_to_camel(disc));
      emitStruct(branchName, b, extraTypes);
      return { disc, branchName, caseName: camel(snake_to_camel(disc)) };
    })
    .sort((a, b) => a.branchName.localeCompare(b.branchName));

  const cases = branches
    .map((b) => `    case ${b.caseName}(${b.branchName})`)
    .join('\n');

  const decodeCases = branches
    .map(
      (b) =>
        `        case "${b.disc}": self = .${b.caseName}(try ${b.branchName}(from: decoder))`
    )
    .join('\n');

  const encodeCases = branches
    .map(
      (b) =>
        `        case .${b.caseName}(let v): try v.encode(to: encoder)`
    )
    .join('\n');

  const code = `public enum ${name}: Codable, Equatable {
${cases}

    private enum DiscKey: String, CodingKey { case op }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: DiscKey.self)
        let op = try c.decode(String.self, forKey: .op)
        switch op {
${decodeCases}
        default:
            throw DecodingError.dataCorruptedError(
                forKey: .op, in: c,
                debugDescription: "Unknown ${name} op '\\(op)'"
            )
        }
    }

    public func encode(to encoder: Encoder) throws {
        switch self {
${encodeCases}
        }
    }
}
`;
  extraTypes.set(name, code);
}

// --- main emit ---------------------------------------------------------

const extraTypes = new Map(); // name → emitted Swift code

// 1. Resolve the recursive node ONCE under the fixed name `VNode` (Finding A).
emitStruct(VNODE_NAME, schema.$defs[vnodeDefKey], extraTypes);

// 2. Emit the root VTreeTimeline struct. Its `frames`/`viewport`/`version`
//    props recurse through swiftType, which emits VFrame (via frames.items.$id),
//    VOp (via ops.items.$id), VOpSet/VOpAdd/VOpRemove, and the nested viewport.
emitStruct('VTreeTimeline', schema, extraTypes);

// Sort extraTypes by name for deterministic output.
const sortedExtras = [...extraTypes.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([, code]) => code)
  .join('\n');

const final = HEADER + '\n' + sortedExtras;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, final);
console.log(`[codegen-vtree-swift] wrote ${outPath}`);
